document.addEventListener(
    "play",
    function(event) {

        if (event.target.tagName !== "VIDEO") {
            return;
        }


        document
            .querySelectorAll("video")
            .forEach(video => {

                if (video !== event.target) {

                    if (
                        typeof video.resetToThumbnail ===
                        "function"
                    ) {

                        video.resetToThumbnail();

                    }

                    else {

                        video.pause();

                        video.currentTime = 0;

                    }

                }

            });

    },
    true
);


