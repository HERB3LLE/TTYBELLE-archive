// =================================
// 날짜별 / 게시물별 그룹 만들기
// =================================

function groupByDate(data) {

    const groups = {};
    const order = [];

    data.forEach(item => {

        const key = item.postId
            ? `post-${item.postId}`
            : `date-${item.date}`;

        if (!groups[key]) {

            groups[key] = {
                date: item.date,
                items: []
            };

            order.push(key);

        }

        groups[key].items.push(item);

    });

    return order.map(key => groups[key]);

}


// =================================
// 화면 표시
// =================================

function render() {

    const archive =
        document.getElementById("archive");

    let filteredItems = [...items];


    // =================================
    // 카테고리 필터
    // =================================

    if (currentFilter !== "all") {

        filteredItems =
            filteredItems.filter(
                item =>
                    item.type === currentFilter
            );

    }


    // =================================
    // 검색
    // =================================

    if (searchText.trim() !== "") {

        const keyword =
            searchText.toLowerCase().trim();

        filteredItems =
            filteredItems.filter(item =>

                item.title
                    .toLowerCase()
                    .includes(keyword)

                ||

                item.date.includes(keyword)

            );

    }


    // =================================
    // 날짜 / 게시물 그룹
    // =================================

    let groups =
        groupByDate(filteredItems);


    // =================================
    // 최신순 / 과거순
    // =================================

    groups.sort((a, b) => {

        const dateA =
            new Date(a.date);

        const dateB =
            new Date(b.date);

        if (currentSort === "new") {

            return dateB - dateA;

        }

        return dateA - dateB;

    });


    archive.innerHTML = "";


    // =================================
    // 자료 없음
    // =================================

    if (groups.length === 0) {

        archive.innerHTML = `
            <div class="empty">
                ${translations[currentLanguage].empty}
            </div>
        `;

        return;

    }


    // =================================
    // 포스트 카드 만들기
    // =================================

    groups.forEach(group => {

        const element =
            document.createElement("article");

        element.className = "item";


        // =================================
        // 슬라이드
        // =================================

        const slider =
            document.createElement("div");

        slider.className = "media-slider";


        const track =
            document.createElement("div");

        track.className = "media-track";


        group.items.forEach(item => {

            const slide =
                document.createElement("div");

            slide.className = "media-slide";


            // =================================
            // PHOTO
            // =================================

            if (item.type === "photo") {

                slide.innerHTML = `

                    <div
                        class="media"
                        onclick="openImage('${item.file}')"
                    >

                        <img
                            src="${item.file}"
                            alt="${item.title}"
                        >

                    </div>

                `;

            }


            // =================================
            // VIDEO
            // =================================

            else if (item.type === "video") {

                slide.innerHTML = `

                    <div class="media">

                        <video
                            src="${item.file}"
                            ${item.thumbnail ? `poster="${item.thumbnail}"` : ""}
                            playsinline
                            preload="metadata"
                        ></video>

                    </div>

                `;

            }


            // =================================
            // REELS
            // =================================

            else if (item.type === "reels") {

                slide.innerHTML = `

                    <div class="media custom-video">

                        <img
                            class="video-thumbnail"
                            src="${item.thumbnail}"
                            alt=""
                        >

                        <video
                            src="${item.file}"
                            playsinline
                            preload="metadata"
                        ></video>

                        <button
                            class="center-play"
                            type="button"
                        >▶</button>

                        <div class="video-bottom">

                            <div class="video-progress">

                                <div class="video-progress-bar"></div>

                            </div>

                            <button
                                class="fullscreen-btn"
                                type="button"
                            >⛶</button>

                        </div>

                    </div>

                `;


                const customVideo =
                    slide.querySelector(".custom-video");

                const video =
                    slide.querySelector("video");

                const thumbnail =
                    slide.querySelector(".video-thumbnail");

                const centerPlay =
                    slide.querySelector(".center-play");

                const progress =
                    slide.querySelector(".video-progress");

                const progressBar =
                    slide.querySelector(".video-progress-bar");

                const fullscreenBtn =
                    slide.querySelector(".fullscreen-btn");


                // =================================
                // 썸네일로 복귀
                // =================================

                function resetToThumbnail() {

                    video.pause();

                    video.currentTime = 0;

                    customVideo.classList.remove("playing");

                    centerPlay.textContent = "▶";

                    centerPlay.classList.remove("hidden");

                    progressBar.style.width = "0%";

                    thumbnail.style.display = "block";

                    video.style.visibility = "hidden";

                }


                // =================================
                // 다른 영상에서 사용할 수 있게 등록
                // =================================

                video.resetToThumbnail =
                    resetToThumbnail;


                // =================================
                // 재생 / 일시정지
                // =================================

                function toggleVideo() {

                    if (video.paused) {

                        video.play();

                    } else {

                        video.pause();

                    }

                }


                // =================================
                // 영상 화면 눌러서 재생 / 일시정지
                // =================================

                video.addEventListener(
                    "click",
                    function() {

                        toggleVideo();

                    }
                );


                // =================================
                // 가운데 ▶ 버튼
                // =================================

                centerPlay.addEventListener(
                    "click",
                    function(event) {

                        event.stopPropagation();

                        toggleVideo();

                    }
                );


                // =================================
                // 재생 시작
                // =================================

                video.addEventListener(
                    "play",
                    function() {

                        thumbnail.style.display = "none";

                        video.style.visibility = "visible";

                        centerPlay.classList.add("hidden");

                        customVideo.classList.add("playing");

                    }
                );


                // =================================
                // 일시정지
                // =================================

                video.addEventListener(
                    "pause",
                    function() {

                        centerPlay.textContent = "▶";

                        centerPlay.classList.remove("hidden");

                        customVideo.classList.remove("playing");

                    }
                );


                // =================================
                // 영상 끝나면 썸네일로 복귀
                // =================================

                video.addEventListener(
                    "ended",
                    function() {

                        resetToThumbnail();

                    }
                );


                // =================================
                // 진행바
                // =================================

                video.addEventListener(
                    "timeupdate",
                    function() {

                        if (video.duration) {

                            const percent =
                                (video.currentTime /
                                video.duration) * 100;

                            progressBar.style.width =
                                percent + "%";

                        }

                    }
                );


                // =================================
                // 진행바 클릭
                // =================================

                progress.addEventListener(
                    "click",
                    function(event) {

                        event.stopPropagation();

                        if (!video.duration) {
                            return;
                        }

                        const rect =
                            progress.getBoundingClientRect();

                        const percent =
                            (event.clientX - rect.left) /
                            rect.width;

                        video.currentTime =
                            percent * video.duration;

                    }
                );


                // =================================
                // 전체화면
                // =================================

                fullscreenBtn.addEventListener(
                    "click",
                    function(event) {

                        event.stopPropagation();


                        if (
                            video.requestFullscreen
                        ) {

                            video.requestFullscreen();

                        }

                        else if (
                            video.webkitEnterFullscreen
                        ) {

                            video.webkitEnterFullscreen();

                        }

                    }
                );


                // =================================
                // 처음에는 썸네일 표시
                // =================================

                video.style.visibility = "hidden";

            }


            track.appendChild(slide);

        });


        slider.appendChild(track);


        // =================================
        // 슬라이드 점
        // =================================

        if (group.items.length > 1) {

            const dots =
                document.createElement("div");

            dots.className = "slider-dots";


            group.items.forEach((item, index) => {

                const dot =
                    document.createElement("span");

                dot.className = "slider-dot";


                if (index === 0) {

                    dot.classList.add("active");

                }


                dots.appendChild(dot);

            });


            slider.appendChild(dots);


            // =================================
            // 현재 슬라이드 표시
            // =================================

            track.addEventListener(
                "scroll",
                function() {

                    const width =
                        slider.clientWidth;


                    const current =
                        Math.round(
                            track.scrollLeft / width
                        );


                    dots
                        .querySelectorAll(".slider-dot")
                        .forEach((dot, index) => {

                            dot.classList.toggle(
                                "active",
                                index === current
                            );

                        });

                }
            );

        }


        element.appendChild(slider);


        // =================================
        // 정보
        // =================================

        const info =
            document.createElement("div");

        info.className = "info";


        const firstItem =
            group.items[0];


        info.innerHTML = `

            <div class="title">
                ${firstItem.title}
            </div>

            <div class="date">
                ${formatDate(group.date)}
            </div>

            <div class="type">
                ${getGroupTypeText(group.items)}
            </div>

        `;


        element.appendChild(info);

        archive.appendChild(element);

    });

}


