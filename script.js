// =================================
// 날짜별 / 게시물별 그룹 만들기
// =================================

function groupByDate(data) {

    const groups = {};
    const order = [];

    data.forEach(item => {

        /*
         * postId가 있는 경우
         * 같은 postId끼리 하나의 포스트로 묶음
         *
         * postId가 없는 경우
         * 기존처럼 같은 날짜끼리 묶음
         */

        const key = item.postId
            ? `post-${item.postId}`
            : `date-${item.date}`;


        if (!groups[key]) {

            groups[key] = {
                date: item.date,
                items: []
            };

            order.push(key);

        }


        groups[key].items.push(item);

    });


    return order.map(key => groups[key]);

}


// =================================
// 화면 표시
// =================================

function render() {

    const archive =
        document.getElementById("archive");

    let filteredItems = [...items];


    // =================================
    // 카테고리 필터
    // =================================

    if (currentFilter !== "all") {

        filteredItems =
            filteredItems.filter(
                item =>
                    item.type === currentFilter
            );

    }


    // =================================
    // 검색
    // =================================

    if (searchText.trim() !== "") {

        const keyword =
            searchText.toLowerCase().trim();

        filteredItems =
            filteredItems.filter(item =>

                item.title
                    .toLowerCase()
                    .includes(keyword)

                ||

                item.date.includes(keyword)

            );

    }


    // =================================
    // 날짜 / 게시물 그룹
    // =================================

    let groups =
        groupByDate(filteredItems);


    // =================================
    // 최신순 / 과거순
    // =================================

    groups.sort((a, b) => {

        const dateA =
            new Date(a.date);

        const dateB =
            new Date(b.date);

        if (currentSort === "new") {

            return dateB - dateA;

        }

        return dateA - dateB;

    });


    archive.innerHTML = "";


    // =================================
    // 자료 없음
    // =================================

    if (groups.length === 0) {

        archive.innerHTML = `
            <div class="empty">
                ${translations[currentLanguage].empty}
            </div>
        `;

        return;

    }


    // =================================
    // 포스트 카드 만들기
    // =================================

    groups.forEach(group => {

        const element =
            document.createElement("article");

        element.className = "item";


        // =================================
        // 슬라이드
        // =================================

        const slider =
            document.createElement("div");

        slider.className = "media-slider";


        const track =
            document.createElement("div");

        track.className = "media-track";


        group.items.forEach(item => {

            const slide =
                document.createElement("div");

            slide.className = "media-slide";


            // =================================
            // PHOTO
            // =================================

            if (item.type === "photo") {

                slide.innerHTML = `

                    <div
                        class="media"
                        onclick="openImage('${item.file}')"
                    >

                        <img
                            src="${item.file}"
                            alt="${item.title}"
                        >

                    </div>

                `;

            }


            // =================================
            // VIDEO
            // =================================

            else if (item.type === "video") {

                slide.innerHTML = `

                    <div class="media">

                        <video
                            src="${item.file}"
                            controls
                            playsinline
                            preload="metadata"
                        ></video>

                    </div>

                `;

            }


            // =================================
            // REELS
            // =================================

            else if (item.type === "reels") {

                slide.innerHTML = `

                    <div class="media">

                        <video
                            src="${item.file}"
                            controls
                            playsinline
                            preload="metadata"
                        ></video>

                    </div>

                `;

            }


            track.appendChild(slide);

        });


        slider.appendChild(track);


        // =================================
        // 슬라이드 점
        // =================================

        if (group.items.length > 1) {

            const dots =
                document.createElement("div");

            dots.className = "slider-dots";


            group.items.forEach((item, index) => {

                const dot =
                    document.createElement("span");

                dot.className = "slider-dot";


                if (index === 0) {

                    dot.classList.add("active");

                }


                dots.appendChild(dot);

            });


            slider.appendChild(dots);


            // =================================
            // 현재 슬라이드 표시
            // =================================

            track.addEventListener(
                "scroll",
                function() {

                    const width =
                        slider.clientWidth;


                    const current =
                        Math.round(
                            track.scrollLeft / width
                        );


                    dots
                        .querySelectorAll(".slider-dot")
                        .forEach((dot, index) => {

                            dot.classList.toggle(
                                "active",
                                index === current
                            );

                        });

                }
            );

        }


        element.appendChild(slider);


        // =================================
        // 정보
        // =================================

        const info =
            document.createElement("div");

        info.className = "info";


        const firstItem =
            group.items[0];


        info.innerHTML = `

            <div class="title">
                ${firstItem.title}
            </div>

            <div class="date">
                ${formatDate(group.date)}
            </div>

            <div class="type">
                ${getGroupTypeText(group.items)}
            </div>

        `;


        element.appendChild(info);

        archive.appendChild(element);

    });

}


// =================================
// 여러 자료의 타입 표시
// =================================

function getGroupTypeText(groupItems) {

    const types =
        [...new Set(
            groupItems.map(item => item.type)
        )];


    return types
        .map(type =>
            translations[currentLanguage][type]
        )
        .join(" · ");

}


